/**
 * Per-repo navigation map generator.
 *
 * Scans a repo's source tree and (re)writes the AUTO section of its MAP.md
 * (between <!-- AUTO:START --> / <!-- AUTO:END --> markers). Everything
 * outside the markers — a "Where to look" table, hand-written notes — is
 * preserved across regeneration.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";
import { scanRepo } from "./scan.mjs";
import { loadConfig } from "./config.mjs";

const START = "<!-- AUTO:START -->";
const END = "<!-- AUTO:END -->";

export function generateMap(root) {
  const repo = basename(root);
  const config = loadConfig(root);
  const structureLines = scanRepo(root, config);

  const auto = [
    "_Generated by `claude-mapper` — do not edit between the markers; run `npx claude-mapper generate` instead._",
    "",
    ...structureLines,
  ].join("\n");

  const mapPath = join(root, "MAP.md");
  let content;
  let action;

  if (existsSync(mapPath)) {
    const cur = readFileSync(mapPath, "utf8");
    if (cur.includes(START) && cur.includes(END)) {
      content = cur.replace(new RegExp(`${START}[\\s\\S]*?${END}`), `${START}\n${auto}\n${END}`);
    } else {
      content = cur.trimEnd() + `\n\n## Structure\n\n${START}\n${auto}\n${END}\n`;
    }
    action = "updated";
  } else {
    content = `# ${repo} — Map

> Per-repo navigation map. Read this before exploring. See the repo's CLAUDE.md/AGENTS.md for rules.

## Structure

${START}
${auto}
${END}

## Where to look (manual — keep terse)

| Task | Start here |
|---|---|
| _add task_ | _path_ |
`;
    action = "created";
  }

  writeFileSync(mapPath, content);
  return { repo, action };
}
