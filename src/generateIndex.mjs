/**
 * Workspace-root orchestrator: regenerates every sub-repo's MAP.md, then
 * writes a small ARCHITECTURE.md index pointing at them.
 *
 * "Repo" here means any immediate child directory of the workspace root that
 * looks like a real project (has package.json, or a .git folder, or matches
 * a user-supplied glob via --match). This is for multi-repo workspaces —
 * running claude-mapper inside a single repo just uses generateMap directly.
 */
import { readdirSync, existsSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { generateMap } from "./generateMap.mjs";

const START = "<!-- AUTO:START -->";
const END = "<!-- AUTO:END -->";

function looksLikeProject(dirPath) {
  return existsSync(join(dirPath, "package.json")) || existsSync(join(dirPath, ".git"));
}

/**
 * @param {string} workspaceRoot
 * @param {{ match?: RegExp, dryRun?: boolean }} [opts] optional filter on directory name
 */
export function generateIndex(workspaceRoot, opts = {}) {
  const entries = readdirSync(workspaceRoot)
    .filter((n) => !n.startsWith(".") && statSync(join(workspaceRoot, n)).isDirectory())
    .filter((n) => (opts.match ? opts.match.test(n) : true))
    .filter((n) => looksLikeProject(join(workspaceRoot, n)))
    .sort();

  const rows = [];
  for (const name of entries) {
    const repoPath = join(workspaceRoot, name);
    try {
      const { action } = generateMap(repoPath, { dryRun: opts.dryRun });
      rows.push(`| \`${name}\` | [\`${name}/MAP.md\`](${name}/MAP.md) | ${action}${opts.dryRun ? " (dry-run)" : ""} |`);
    } catch (err) {
      rows.push(`| \`${name}\` | — | generation failed: ${err.message} |`);
    }
  }

  const auto = [
    "_Generated by `claude-mapper`. Each repo has its own `MAP.md` — open that, not this whole file._",
    "",
    "| Repo | Map | Status |",
    "|---|---|---|",
    ...rows,
  ].join("\n");

  const archPath = join(workspaceRoot, "ARCHITECTURE.md");
  const existing = existsSync(archPath) ? readFileSync(archPath, "utf8") : "";
  const startIdx = existing.indexOf(START);
  const endIdx = existing.indexOf(END);

  let output;
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    output = existing.slice(0, startIdx) + `${START}\n${auto}\n${END}` + existing.slice(endIdx + END.length);
  } else {
    output = `# Workspace — Navigation Index

> Small index only. Per-repo detail lives in \`<repo>/MAP.md\` — open the one you need.
> Regenerate everything: \`npx claude-mapper generate --all\`.
> Volatile lists are auto-derived from folders; if a path is wrong, the repo moved — rerun the generator.

## Repos

${START}
${auto}
${END}

## Conventions (manual — keep terse)

- _Add workspace-wide conventions here — this section is never touched by regeneration._

## Keep maps current

If you move/rename/add a folder, feature, domain, or route, rerun the generator (the AUTO sections refresh from disk). Manual sections you update by hand — the generator only rewrites text between AUTO:START/AUTO:END.
`;
  }

  if (!opts.dryRun) {
    writeFileSync(archPath, output);
  }
  return { repoCount: entries.length };
}
